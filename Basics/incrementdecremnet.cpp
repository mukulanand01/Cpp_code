#include<iostream>
using namespace std;
int main (){
  // increment decerement operators and comments (x++ or ++x = (x=x+1))
  int x = 5;
cout<<x<<endl;
++x; // pre increment -> x = x + 1
cout<<x<<endl;
x++; // post increment
cout<<x<<endl;
x--; // x = x-1; post increment
cout<<x<<endl;
--x; // x = x-1; pre increment
cout<<x<<endl;
}